# ===================== 服务端口协议（v19.4） =====================
# 只定义接口，不 import 任何业务实现；app 负责装配。

from typing import Any, Iterable, Optional, Protocol


class MessageStore(Protocol):
    def append(self, user_id: str, target_id: str, content: str, role: str,
               channel: str = "qq", thread_id: Optional[str] = None,
               message_id: Optional[str] = None, meta: Any = None) -> bool: ...

    def recent(self, target_id: str, limit: int = 100,
               before_id: Optional[int] = None,
               user_id: Optional[str] = None) -> Iterable[dict]: ...


class LifePort(Protocol):
    def state_line(self, target_id: str) -> str: ...
    def relation_line(self, target_id: str) -> str: ...
    def digest_line(self, target_id: str) -> str: ...


class HookRegistry(Protocol):
    def register(self, name: str, fn: Any) -> None: ...
    def cancel(self, name: str) -> None: ...


class Cache(Protocol):
    def get(self, namespace: str, key: str, default: Any = None) -> Any: ...
    def set(self, namespace: str, key: str, value: Any, ttl: float = 0) -> None: ...
    def invalidate(self, namespace: str) -> None: ...
